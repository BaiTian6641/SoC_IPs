"""Regenerate sv_ip_library.core (FuseSoC CAPI=2) from the repo filelists.

Single source of truth: filelists/interconnect.f (+common.f), ips/NN_*/filelist.f
and the LINT/TB tables in the Makefile (read through `make -s tables`).

    python3 scripts/gen_fusesoc_core.py            # rewrite sv_ip_library.core
    python3 scripts/gen_fusesoc_core.py --check    # exit 1 if the file is stale
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "sv_ip_library.core")
NAME = "open:soc:sv_peripherals_interconnect_suite:3.0.0"


def expand(flist, seen=None, incdirs=None):
    """Return ordered, de-duplicated (files, incdirs) for a .f file (recursing on -f)."""
    seen = seen if seen is not None else []
    incdirs = incdirs if incdirs is not None else []
    for raw in open(os.path.join(ROOT, flist)):
        line = raw.split("#")[0].strip()
        if not line:
            continue
        if line.startswith("+incdir+"):
            d = line[len("+incdir+"):].strip()
            if d and d not in incdirs:
                incdirs.append(d)
            continue
        if line.startswith("-f "):
            expand(line[3:].strip(), seen, incdirs)
        elif line not in seen:
            seen.append(line)
    return seen, incdirs


def expand_tokens(tokens):
    """Expand a list of Makefile tokens (supporting -f <flist>, +incdir+<dir>, and plain paths)."""
    files, incdirs = [], []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok == "-f" and i + 1 < len(tokens):
            expand(tokens[i + 1], files, incdirs)
            i += 2
        elif tok.startswith("+incdir+"):
            d = tok[len("+incdir+"):].strip()
            if d and d not in incdirs:
                incdirs.append(d)
            i += 1
        elif tok.startswith("-"):
            # Skip other tool flags if any
            i += 1
        else:
            if tok not in files:
                files.append(tok)
            i += 1
    return files, incdirs


def tables():
    out = subprocess.run(["make", "-s", "-C", ROOT, "tables"], capture_output=True, text=True, check=True).stdout
    ips, lints, tbs = [], [], []
    for ln in out.splitlines():
        f = ln.split("|")
        if f[0] == "LINT":
            lints.append((f[1], f[2].split()))
        elif f[0] == "TB":
            tbs.append((f[1], f[2], f[3].split(), f[4].split()))
        elif f[0] == "IPS":
            ips = f[1].split()
    return ips, lints, tbs


def fileset(name, files, comment=None, include_files=None):
    s = ""
    if comment:
        s += f"  # {comment}\n"
    s += f"  {name}:\n    files:\n"
    for inc_path, inc_dir in (include_files or []):
        s += f"      - {inc_path}: {{is_include_file: true, include_path: {inc_dir}}}\n"
    for f in files:
        s += f"      - {f}\n"
    s += "    file_type: systemVerilogSource\n\n"
    return s


def discover_svh(incdir):
    """Return sorted repo-relative .svh files directly inside incdir."""
    full = os.path.join(ROOT, incdir)
    if not os.path.isdir(full):
        return []
    return [
        (os.path.join(incdir, fn), incdir)
        for fn in sorted(os.listdir(full))
        if fn.endswith(".svh")
    ]


def main():
    ips, lints, tbs = tables()
    lib, lib_incdirs = expand("filelists/interconnect.f")
    ipfiles = {}
    ip_incdirs = {}
    for d in ips:
        fl = f"ips/{d}/filelist.f"
        if os.path.exists(os.path.join(ROOT, fl)):
            f_list, inc_list = expand(fl)
            ipfiles[d] = [f for f in f_list if f not in lib]
            ip_incdirs[d] = [inc for inc in inc_list if inc not in lib_incdirs]
        else:
            ipfiles[d] = []
            ip_incdirs[d] = []

    has_vkit = os.path.exists(os.path.join(ROOT, "tb/vkit/filelist.f"))
    vkit_files, vkit_incdirs = expand("tb/vkit/filelist.f") if has_vkit else ([], [])

    o = "CAPI=2:\n# GENERATED by scripts/gen_fusesoc_core.py -- do not edit by hand.\n"
    o += f'name: "{NAME}"\n'
    o += ('description: "SystemVerilog IP library: common primitives, WB/AXI4/TL/APB/AXI-Stream interconnect, '
          f'{len(ips)} bus-agnostic peripheral/accelerator IPs with quad-bus wrappers"\n\n')
    o += "filesets:\n"
    lib_svh = []
    for incdir in lib_incdirs:
        lib_svh.extend(discover_svh(incdir))
    if not lib_svh:
        lib_svh = [("common/include/sv_ip_macros.svh", "common/include")]
    o += fileset("inc", [], "shared RTL headers", include_files=lib_svh)
    o += fileset("lib", lib, "common + interconnect (packages first)")
    for d in ips:
        svh = []
        for incdir in ip_incdirs[d]:
            svh.extend(discover_svh(incdir))
        o += fileset("ip_" + d, ipfiles[d], include_files=svh)
    o += fileset("tb_bfm", ["tb/common/tb_bfm_pkg.sv", "tb/common/tb_sim_ram.sv"], "shared BFMs")
    o += fileset("tb_bfm_inc", [], include_files=[("tb/common/tb_bfm_tasks.svh", "tb/common")])
    if has_vkit:
        vkit_svh = []
        for incdir in vkit_incdirs:
            vkit_svh.extend(discover_svh(incdir))
        o += fileset("tb_vkit", vkit_files, "UVM-style verification kit", include_files=vkit_svh)

    tb_uses_vkit = {}
    for name, src, tips, extra in tbs:
        uses_vkit = has_vkit and ("tb/vkit/filelist.f" in extra)
        tb_uses_vkit[name] = uses_vkit
        extra_files, extra_incdirs = expand_tokens(extra)
        if uses_vkit:
            extra_files = [f for f in extra_files if f not in vkit_files]
            extra_incdirs = [d for d in extra_incdirs if d not in vkit_incdirs]
        extra_svh = []
        for incdir in extra_incdirs:
            extra_svh.extend(discover_svh(incdir))
        tb_files = extra_files + ([src] if src not in extra_files else [])
        o += fileset("tbsrc_" + name, tb_files, include_files=extra_svh)

    vopt = ["-Wall", "-Wno-UNUSEDSIGNAL", "-Wno-UNUSEDPARAM", "-Wno-DECLFILENAME", "-Wno-PINCONNECTEMPTY"]
    o += "targets:\n"
    o += "  default:\n    description: All RTL (no testbenches)\n    filesets: [inc, lib, " + ", ".join("ip_" + d for d in ips) + "]\n\n"
    for top, tips in lints:
        o += f"  lint_{top}:\n    default_tool: verilator\n    filesets: [inc, lib" + "".join(f", ip_{d}" for d in tips) + "]\n"
        o += f"    toplevel: {top}\n    tools:\n      verilator:\n        mode: lint-only\n        verilator_options: [{', '.join(vopt)}]\n\n"
    for name, src, tips, extra in tbs:
        o += f"  sim_{name}:\n    description: Self-checking testbench (Verilator --binary --timing)\n    default_tool: verilator\n"
        fsets = ["inc", "lib"] + [f"ip_{d}" for d in tips] + ["tb_bfm", "tb_bfm_inc"]
        if tb_uses_vkit[name]:
            fsets.append("tb_vkit")
        fsets.append(f"tbsrc_{name}")
        o += f"    filesets: [{', '.join(fsets)}]\n"
        o += f"    toplevel: {name}\n    tools:\n      verilator:\n        mode: cc\n"
        o += f"        verilator_options: [--binary, --timing, {', '.join(vopt)}, -Wno-TIMESCALEMOD]\n\n"

    if "--check" in sys.argv:
        sys.exit(0 if open(CORE).read() == o else 1)
    open(CORE, "w").write(o)
    print(f"wrote {CORE}: {len(ips)} IP filesets, {len(lints)} lint targets, {len(tbs)} sim targets")


if __name__ == "__main__":
    main()

"""Generate rtl/crypto_sha_pkg.sv: SHA-2 round constants and initial hash values.

FIPS 180-4 defines them as the first 32/64 fractional bits of the square/cube roots
of the first primes.  They are derived here with exact integer arithmetic (no floats)
and the resulting package is validated by the testbench against Python's hashlib.

usage: gen_sha_consts.py [out.sv]
"""
import sys


def primes(n):
    out, c = [], 2
    while len(out) < n:
        if all(c % p for p in out):
            out.append(c)
        c += 1
    return out


def iroot(n, k):
    lo, hi = 0, 1 << ((n.bit_length() // k) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** k <= n:
            lo = mid
        else:
            hi = mid - 1
    return lo


def frac_root(p, k, bits):
    # floor(2^bits * frac(p^(1/k)))
    return iroot(p << (bits * k), k) & ((1 << bits) - 1)


def main():
    p = primes(80)
    k256 = [frac_root(x, 3, 32) for x in p[:64]]
    k512 = [frac_root(x, 3, 64) for x in p[:80]]
    h256 = [frac_root(x, 2, 32) for x in p[:8]]
    h512 = [frac_root(x, 2, 64) for x in p[:8]]
    h384 = [frac_root(x, 2, 64) for x in p[8:16]]
    h224 = [x & 0xFFFFFFFF for x in h384]
    L = []
    L.append("// SPDX-License-Identifier: Apache-2.0")
    L.append("// crypto_sha_pkg.sv - SHA-2 constants (FIPS 180-4). GENERATED by tools/gen_sha_consts.py - do not edit.")
    L.append("")
    L.append("package crypto_sha_pkg;")
    L.append("")

    def arr(name, vals, w):
        L.append("  localparam logic [%d:0] %s [%d] = '{" % (w - 1, name, len(vals)))
        for i in range(0, len(vals), 4):
            row = ", ".join("%d'h%0*x" % (w, w // 4, v) for v in vals[i:i + 4])
            L.append("    " + row + ("," if i + 4 < len(vals) else ""))
        L.append("  };")
        L.append("")

    arr("K256", k256, 32)
    arr("K512", k512, 64)
    arr("H0_SHA256", h256, 32)
    arr("H0_SHA224", h224, 32)
    arr("H0_SHA512", h512, 64)
    arr("H0_SHA384", h384, 64)
    L.append("endpackage : crypto_sha_pkg")
    txt = "\n".join(L) + "\n"
    if len(sys.argv) > 1:
        open(sys.argv[1], "w").write(txt)
    else:
        sys.stdout.write(txt)


if __name__ == "__main__":
    main()

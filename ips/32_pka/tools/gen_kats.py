#               into ips/32_pka/tb/pka_kats.svh using pure Python 3 stdlib.

import os
import random


def is_prime(n: int, k: int = 20) -> bool:
    if n < 2 or n % 2 == 0:
        return n == 2
    r, d = 0, n - 1
    while d % 2 == 0:
        r += 1
        d //= 2
    rng = random.Random(n & 0xFFFFFFFF)
    for _ in range(k):
        a = rng.randrange(2, n - 1)
        x = pow(a, d, n)
        if x == 1 or x == n - 1:
            continue
        for _ in range(r - 1):
            x = (x * x) % n
            if x == n - 1:
                break
        else:
            return False
    return True


def next_prime_bits(bits: int, seed: int) -> int:
    rng = random.Random(seed)
    while True:
        cand = rng.getrandbits(bits) | (1 << (bits - 1)) | 1
        if is_prime(cand):
            return cand


def le_bytes_to_int(hex_str: str) -> int:
    return int.from_bytes(bytes.fromhex(hex_str), "little")


def x25519_ref(k_int: int, u_int: int) -> int:
    p = (1 << 255) - 19
    k = (k_int & ~7) & ~(1 << 255) | (1 << 254)
    x_1 = (u_int & ((1 << 255) - 1)) % p
    x_2, z_2, x_3, z_3, swap = 1, 0, x_1, 1, 0
    for t in range(254, -1, -1):
        k_t = (k >> t) & 1
        swap ^= k_t
        if swap:
            x_2, x_3 = x_3, x_2
            z_2, z_3 = z_3, z_2
        swap = k_t
        a = (x_2 + z_2) % p
        aa = (a * a) % p
        b = (x_2 - z_2) % p
        bb = (b * b) % p
        e = (aa - bb) % p
        c = (x_3 + z_3) % p
        d = (x_3 - z_3) % p
        da = (d * a) % p
        cb = (c * b) % p
        x_3 = pow(da + cb, 2, p)
        z_3 = (x_1 * pow(da - cb, 2, p)) % p
        x_2 = (aa * bb) % p
        z_2 = (e * (aa + 121665 * e)) % p
    if swap:
        x_2, x_3 = x_3, x_2
        z_2, z_3 = z_3, z_2
    return (x_2 * pow(z_2, p - 2, p)) % p


P256_P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
P256_N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
P256_G = (
    0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
    0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5,
)


def p256_add_aff(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and (y1 + y2) % P256_P == 0:
        return None
    if p1 == p2:
        lam = ((3 * x1 * x1 - 3) * pow(2 * y1, P256_P - 2, P256_P)) % P256_P
    else:
        lam = ((y2 - y1) * pow(x2 - x1, P256_P - 2, P256_P)) % P256_P
    x3 = (lam * lam - x1 - x2) % P256_P
    y3 = (lam * (x1 - x3) - y1) % P256_P
    return (x3, y3)


def p256_mul_aff(k: int, pt):
    r = None
    q = pt
    while k:
        if k & 1:
            r = p256_add_aff(r, q)
        q = p256_add_aff(q, q)
        k >>= 1
    return r


def fmt_array(name: str, val: int, nwords: int) -> str:
    limbs = [(val >> (32 * i)) & 0xFFFFFFFF for i in range(nwords)]
    items = [f"32'h{w:08x}" for w in limbs]
    lines = [f"localparam logic [31:0] {name} [0:{nwords-1}] = '{{"]
    for i in range(0, len(items), 8):
        comma = "," if (i + 8) < len(items) else ""
        lines.append("  " + ", ".join(items[i : i + 8]) + comma)
    lines.append("};")
    return "\n".join(lines)


def main():
    out_lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Auto-generated by ips/32_pka/tools/gen_kats.py - DO NOT EDIT BY HAND",
        "",
    ]

    e = 65537
    for bits, sp, sq in [(256, 101, 102), (512, 201, 202), (1024, 301, 302), (2048, 401, 402)]:
        while True:
            p = next_prime_bits(bits // 2, sp)
            q = next_prime_bits(bits // 2, sq)
            phi = (p - 1) * (q - 1)
            if p != q:
                try:
                    d = pow(e, -1, phi)
                    break
                except ValueError:
                    pass
            sp += 10
            sq += 10
        n = p * q
        nw = bits // 32
        rng = random.Random(bits + 999)
        m = rng.randrange(2, n - 1)
        c = pow(m, e, n)
        assert pow(c, d, n) == m
        out_lines.append(f"// RSA-{bits} (e=65537)")
        out_lines.append(fmt_array(f"RSA{bits}_N", n, nw))
        out_lines.append(fmt_array(f"RSA{bits}_D", d, nw))
        out_lines.append(fmt_array(f"RSA{bits}_M", m, nw))
        out_lines.append(fmt_array(f"RSA{bits}_C", c, nw))
        out_lines.append("")

    # RSA-4096 smoke (4096-bit word-width modexp with e=65537)
    rng4096 = random.Random(4096)
    n4096 = rng4096.getrandbits(4096) | (1 << 4095) | 1
    m4096 = rng4096.randrange(2, n4096 - 1)
    c4096 = pow(m4096, e, n4096)
    out_lines.append("// RSA-4096 smoke (e=65537)")
    out_lines.append(fmt_array("RSA4096_N", n4096, 128))
    out_lines.append(fmt_array("RSA4096_M", m4096, 128))
    out_lines.append(fmt_array("RSA4096_C", c4096, 128))
    out_lines.append("")

    # RFC 7748 X25519
    k1 = le_bytes_to_int("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4")
    u1 = le_bytes_to_int("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")
    o1 = le_bytes_to_int("c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552")
    assert x25519_ref(k1, u1) == o1

    k2 = le_bytes_to_int("4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d")
    u2 = le_bytes_to_int("e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493")
    o2 = le_bytes_to_int("95cbde9476e8907d7aade45cb4b873f88b595a68799fa152e6f8f7647aac7957")
    assert x25519_ref(k2, u2) == o2

    alice_k = le_bytes_to_int("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
    alice_p = le_bytes_to_int("8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a")
    bob_k   = le_bytes_to_int("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
    bob_p   = le_bytes_to_int("de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f")
    dh_sh   = le_bytes_to_int("4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742")
    assert x25519_ref(alice_k, 9) == alice_p
    assert x25519_ref(bob_k, 9) == bob_p
    assert x25519_ref(alice_k, bob_p) == dh_sh
    assert x25519_ref(bob_k, alice_p) == dh_sh

    out_lines.append("// RFC 7748 X25519")
    for nm, val in [
        ("X25519_V1_K", k1), ("X25519_V1_U", u1), ("X25519_V1_OUT", o1),
        ("X25519_V2_K", k2), ("X25519_V2_U", u2), ("X25519_V2_OUT", o2),
        ("X25519_ALICE_K", alice_k), ("X25519_ALICE_PUB", alice_p),
        ("X25519_BOB_K", bob_k), ("X25519_BOB_PUB", bob_p),
        ("X25519_DH_SHARED", dh_sh),
    ]:
        out_lines.append(fmt_array(nm, val, 8))
    out_lines.append("")

    # NIST P-256
    p1g = p256_mul_aff(1, P256_G)
    p2g = p256_mul_aff(2, P256_G)
    p3g = p256_mul_aff(3, P256_G)
    p4g = p256_mul_aff(4, P256_G)
    k_rfc = 0xC9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721
    q_rfc = p256_mul_aff(k_rfc, P256_G)
    k_cust = 0xDEADBEEF123456789ABCDEF00FEDCBA98765432100112233445566778899AABB
    q_cust = p256_mul_aff(k_cust, p3g)

    out_lines.append("// NIST P-256")
    for nm, val in [
        ("P256_1G_X", p1g[0]), ("P256_1G_Y", p1g[1]),
        ("P256_2G_X", p2g[0]), ("P256_2G_Y", p2g[1]),
        ("P256_3G_X", p3g[0]), ("P256_3G_Y", p3g[1]),
        ("P256_4G_X", p4g[0]), ("P256_4G_Y", p4g[1]),
        ("P256_RFC_K", k_rfc), ("P256_RFC_QX", q_rfc[0]), ("P256_RFC_QY", q_rfc[1]),
        ("P256_CUST_K", k_cust), ("P256_CUST_QX", q_cust[0]), ("P256_CUST_QY", q_cust[1]),
        ("P256_ORD_N", P256_N),
    ]:
        out_lines.append(fmt_array(nm, val, 8))

    out_path = os.path.join(os.path.dirname(__file__), "..", "tb", "pka_kats.svh")
    with open(out_path, "w") as f:
        f.write("\n".join(out_lines) + "\n")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()

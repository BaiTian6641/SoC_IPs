"""Generates ips/20_hub75/rtl/hub75_gamma_pkg.sv (4 x 256-entry 12-bit gamma ROM presets).

Preset 0: gamma 2.2   out = round(4095 * (i/255)^2.2)
Preset 1: linear      out = round(4095 * i / 255)
Preset 2: gamma 2.8   out = round(4095 * (i/255)^2.8)
Preset 3: gamma 1.8   out = round(4095 * (i/255)^1.8)

Run from repo root:  python3 ips/20_hub75/scripts/gen_hub75_pkg.py
The generated file is checked in so that no tool needs Python at build time.
"""
import os

GAMMAS = [2.2, 1.0, 2.8, 1.8]


def table(g):
    return [int(round(4095.0 * ((i / 255.0) ** g))) for i in range(256)]


def main():
    out = []
    out.append("// SPDX-License-Identifier: Apache-2.0")
    out.append("// hub75_gamma_pkg.sv - GENERATED by scripts/gen_hub75_pkg.py. DO NOT EDIT.")
    out.append("// 12-bit linear-light values for 8-bit input codes (4 presets).")
    out.append("package hub75_gamma_pkg;")
    for n, g in enumerate(GAMMAS):
        t = table(g)
        out.append("")
        out.append("  // Preset %d: gamma %.1f" % (n, g))
        out.append("  localparam logic [11:0] GAMMA_ROM_%d [256] = '{" % n)
        for r in range(16):
            row = ", ".join("12'h%03X" % v for v in t[r * 16:(r + 1) * 16])
            out.append("    " + row + ("," if r != 15 else ""))
        out.append("  };")
    out.append("")
    out.append("  function automatic logic [11:0] gamma_rom(input logic [1:0] preset, input logic [7:0] idx);")
    out.append("    unique case (preset)")
    for n in range(4):
        out.append("      2'd%d: return GAMMA_ROM_%d[idx];" % (n, n))
    out.append("      default: return GAMMA_ROM_0[idx];")
    out.append("    endcase")
    out.append("  endfunction")
    out.append("")
    out.append("endpackage : hub75_gamma_pkg")
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "rtl", "hub75_gamma_pkg.sv")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
